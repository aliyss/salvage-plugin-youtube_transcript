import { serve, PluginError } from "./sdk";
import { readTranscript } from "./youtube";

export default () =>
  serve(async ({ command, params }) => {
    if (command !== "read-transcript") {
      throw new PluginError("unsupported", `Unknown command ${command}.`);
    }

    const url = params.subject?.link?.url;
    if (!url) {
      throw new PluginError("bad_subject", "This entry has no link.");
    }

    const settings = params.settings ?? {};
    const text = await readTranscript(url, {
      language:
        typeof settings.language === "string" ? settings.language : undefined,
      autoGenerated: settings.autoGenerated !== false,
      maxLines:
        typeof settings.maxLines === "number" ? settings.maxLines : 0,
    });

    return { kind: "youtube-transcript", text };
  });
